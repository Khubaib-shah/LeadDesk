// Deterministic date offset generator for consistent mock data
const getIsoDate = (daysOffset: number, hours = 10, minutes = 0): string => {
  const d = new Date();
  d.setDate(d.getDate() + daysOffset);
  d.setHours(hours, minutes, 0, 0);
  return d.toISOString();
};

